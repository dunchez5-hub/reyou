export function computeResult5(answers: Record<string, unknown>, verbLead: string, verbFlat: boolean) {
  const raw = {};
  DRIVERS.forEach((d) => (raw[d] = 0));
  let sumW = 0;

  const fq = falsificationQuestion(verbLead, verbFlat);
  const all = [...QUESTIONS5, fq];

  all.forEach((q) => {
    const a = answers[q.id];
    if (a == null) return;
    if (q.kind === "scale" || q.kind === "slider") return; // это шкала Б

    sumW += q.weight;

    if (q.kind === "single") {
      const opt = q.options.find((o) => o.id === a);
      if (opt && opt.score) Object.entries(opt.score).forEach(([p, v]) => (raw[p] += v * q.weight));
    }
    if (q.kind === "distribute") {
      q.items.forEach((item) => {
        raw[item.pole] += (a[item.pole] || 0) * q.weight;
      });
    }
  });

  const total = DRIVERS.reduce((s, p) => s + raw[p], 0) || 1;
  const pct = {};
  DRIVERS.forEach((p) => (pct[p] = (raw[p] / total) * 100));

  let H = (25 / Math.sqrt(sumW || 1)) * Math.sqrt(6 / 4);
  H = Math.max(4, Math.min(30, H));

  const ranked = [...DRIVERS].sort((a, b) => pct[b] - pct[a]);
  const lead = ranked[0];
  const second = ranked[1];
  const flat = pct[lead] < 25;

  /* --- шкала Б: социальная плотность ---------------------------- */
  let dSum = 0;
  let dW = 0;
  let behavioural = null;
  let selfReport = null;

  QUESTIONS5.filter((q) => q.density).forEach((q) => {
    const a = answers[q.id];
    if (a == null) return;
    if (q.kind === "scale") {
      const v = q.reverse ? 6 - a : a;
      const s100 = ((v - 1) / 4) * 100;
      dSum += s100 * q.weight;
      dW += q.weight;
      behavioural = behavioural == null ? s100 : (behavioural + s100) / 2;
    }
    if (q.kind === "slider") {
      dSum += a * q.weight;
      dW += q.weight;
      selfReport = a;
    }
  });

  // фальсификационный вопрос может двигать плотность
  const fa = answers[FALSIFICATION_ID];
  if (fa && fq._bank[fa] && fq._bank[fa].density != null) {
    dSum += (50 + fq._bank[fa].density) * 0.4;
    dW += 0.4;
  }

  const density = dW > 0 ? dSum / dW : 50;
  let densityH = dW > 0 ? 25 / Math.sqrt(dW) : 25;
  densityH = Math.max(4, Math.min(30, densityH));

  const densityMismatch =
    behavioural != null && selfReport != null && Math.abs(behavioural - selfReport) > 20;

  /* --- результат фальсификации ---------------------------------- */
  let falsification = null;
  if (fa) {
    const bank = fq._bank;
    if (fa === bank.hypothesisSide) {
      falsification = "confirmed";
    } else {
      const chosenScore = bank[fa].score || {};
      const chosenTop = Object.keys(chosenScore).sort(
        (x, y) => (chosenScore[y] || 0) - (chosenScore[x] || 0)
      )[0];
      const delta = chosenTop ? Math.abs((pct[chosenTop] || 0) - (pct[lead] || 0)) : 99;
      falsification = delta <= 8 ? "shifted" : "broken";
    }
  }

  return {
    raw, pct, sumW, H, ranked, lead, second, flat,
    density, densityH, densityMismatch, behavioural, selfReport,
    falsification,
  };
}

export function isComplete5(q, a) {
  if (a == null) return false;
  if (q.kind === "distribute") {
    const poles = q.items.map((i) => i.pole);
    return poles.reduce((s, p) => s + (a[p] || 0), 0) === q.total;
  }
  return true;
}

export function driverLevel(v: number) {
  return v >= 25 ? "high" : v >= 12 ? "mid" : "low";
}

export function densityLevel(v: number) {
  return v >= 65 ? "high" : v <= 35 ? "low" : "mid";
}

