export function directionLine(verbLead: string, materialLead: string, driverLead: string, verbFlat: boolean) {
  const verb = VERB_PHRASE[verbLead] || "работаешь";
  const pole = POLE_PHRASE[materialLead] || "своём поле";
  const driver = DRIVER_META[driverLead] ? DRIVER_META[driverLead].name.toLowerCase() : "—";
  if (verbFlat || !verbLead) {
    return `Твоё поле — ${pole}, а держит тебя ${driver}. Глагол пока не определился — его уточнят следующие главы.`;
  }
  return `Ты — тот, кто ${verb} в ${pole}, и тебя держит ${driver}.`;
}

