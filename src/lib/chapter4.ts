/* ------------------------------------------------------------------ */
/*  Скоринг: взвешенное среднее по каждой шкале, перевод 1–5 → 0–100    */
/* ------------------------------------------------------------------ */

function to100(v: number) {
  return ((v - 1) / 4) * 100;
}

export function computeResult4(answers: Record<string, unknown>) {
  let sumA = 0;
  let wA = 0;
  let sumB = 0;
  let wB = 0;

  QUESTIONS4.forEach((q) => {
    const a = answers[q.id];
    if (a == null) return;

    if (q.kind === "scale") {
      const v = q.reverse ? 6 - a : a;
      if (q.scaleId === "A") { sumA += v * q.weight; wA += q.weight; }
      else { sumB += v * q.weight; wB += q.weight; }
    }
    if (q.kind === "single4") {
      const idx = q.options.findIndex((o) => o.id === a);
      if (idx < 0) return;
      const v = CODE4[idx];
      if (q.scaleId === "A") { sumA += v * q.weight; wA += q.weight; }
      else { sumB += v * q.weight; wB += q.weight; }
    }
    if (q.kind === "single4ab") {
      const opt = q.options.find((o) => o.id === a);
      if (!opt) return;
      sumA += opt.a * q.weight; wA += q.weight;
      sumB += opt.b * q.weight; wB += q.weight;
    }
  });

  const rawA = wA > 0 ? sumA / wA : 3;
  const rawB = wB > 0 ? sumB / wB : 3;
  const pctA = to100(rawA);
  const pctB = to100(rawB);

  const HA = Math.max(4, Math.min(25, 25 / Math.sqrt(wA || 1)));
  const HB = Math.max(4, Math.min(25, 25 / Math.sqrt(wB || 1)));

  const thinkType = pctA >= 65 ? "analytic" : pctA <= 35 ? "figurative" : "mixed";
  const focusType = pctB >= 65 ? "system" : pctB <= 35 ? "detail" : "mixed";

  const quadrant =
    thinkType === "figurative" && focusType === "detail" ? "MASTER" :
    thinkType === "figurative" ? "VISIONARY" :
    focusType === "detail" ? "INVESTIGATOR" :
    "ARCHITECT";

  return { pctA, pctB, HA, HB, wA, wB, thinkType, focusType, quadrant };
}

