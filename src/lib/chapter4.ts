// ожидаемое соответствие глагол → стиль (не показывается пользователю как
// таблица, используется только для сверки)
const EXPECTED = {
  IS: { think: "analytic", focus: "system" }, // Исследовать
  OR: { focus: "system" },                     // Организовывать — любой think
  CHI: { focus: "detail" },                     // Чинить — любой think
  SO: { think: "figurative" },                  // Создавать — любой focus
  PE: { think: "analytic" },                    // Передавать
  // Убеждать — не завязан на стиль мышления
};

export function crossCheck4(verbLead: string, thinkType: string, focusType: string) {
  const exp = EXPECTED[verbLead];
  if (!exp) return null; // Убеждать или неизвестный глагол — нет ожидания, нет сверки
  const thinkOk = !exp.think || exp.think === thinkType || thinkType === "mixed";
  const focusOk = !exp.focus || exp.focus === focusType || focusType === "mixed";
  return { matched: thinkOk && focusOk, expected: exp };
}

