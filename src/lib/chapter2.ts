export function computeResult2(answers: Record<string, unknown>) {
  const raw = { L: 0, S: 0, M: 0, O: 0 };
  let sumW = 0;

  QUESTIONS2.forEach((q) => {
    if (!IPSATIVE_IDS2.includes(q.id)) return;
    const a = answers[q.id];
    if (a == null) return;
    sumW += q.weight;

    if (q.kind === "single") {
      const opt = q.options.find((o) => o.id === a);
      if (opt) Object.entries(opt.score).forEach(([p, v]) => (raw[p] += v * q.weight));
    }
    if (q.kind === "distribute") {
      q.items.forEach((item) => {
        raw[item.pole] += (a[item.pole] || 0) * q.weight;
      });
    }
  });

  const total = ORDER2.reduce((s, p) => s + raw[p], 0) || 1;
  const pct = {};
  ORDER2.forEach((p) => (pct[p] = (raw[p] / total) * 100));

  const norm = {};
  QUESTIONS2.filter((q) => q.kind === "scale").forEach((q) => {
    const a = answers[q.id];
    if (a == null) return;
    const v = q.reverse ? 6 - a : a;
    norm[q.pole] = ((v - 1) / 4) * 100;
  });

  const ranked = [...ORDER2].sort((a, b) => pct[b] - pct[a]);
  const lead = ranked[0];

  // Q7 — «что давалось легко». Если полюс ответа не совпадает с ведущим —
  // это и есть «слепое пятно» (см. блок ниже).
  const q7Opt = QUESTIONS2.find((q) => q.id === "c2q7").options.find(
    (o) => o.id === answers.c2q7
  );
  const q7Pole = q7Opt ? Object.keys(q7Opt.score)[0] : null;
  const blindSpot = q7Pole && q7Pole !== lead ? q7Pole : null;

  return { raw, pct, norm, sumW, ranked, lead, blindSpot };
}

export function isComplete2(q, a) {
  if (a == null) return false;
  if (q.kind === "distribute")
    return ORDER2.reduce((s, p) => s + (a[p] || 0), 0) === q.total;
  return true;
}

