/*  Объединённый профиль (главы 1 + 2) для диаграммы и коридора H       */
/* ------------------------------------------------------------------ */

export function chapterPctFromMeasurements(measurements: any[], chapter: string) {
  const pct = { L: 0, S: 0, M: 0, O: 0 };
  let sumW = 0;
  ORDER2.forEach((p) => {
    const m = measurements.find((x) => x.chapter === chapter && x.pole === p && x.kind === "ipsative");
    if (m) {
      pct[p] = m.value;
      sumW = m.weight; // одинаковый вес на все полюса внутри главы
    }
  });
  return { pct, sumW };
}

export function combineProfile(measurements: any[]) {
  const acc = { L: { sw: 0, swv: 0 }, S: { sw: 0, swv: 0 }, M: { sw: 0, swv: 0 }, O: { sw: 0, swv: 0 } };
  measurements.forEach((m) => {
    if (m.kind !== "ipsative") return;
    if (!acc[m.pole]) return;
    acc[m.pole].sw += m.weight;
    acc[m.pole].swv += m.weight * m.value;
  });
  const pct = {};
  ORDER2.forEach((p) => (pct[p] = acc[p].sw > 0 ? acc[p].swv / acc[p].sw : 0));
  const sumW = acc.L.sw || acc.S.sw || acc.M.sw || acc.O.sw || 0;
  let H = sumW > 0 ? 25 / Math.sqrt(sumW) : 25;
  H = Math.max(4, Math.min(25, H));
  const ranked = [...ORDER2].sort((a, b) => pct[b] - pct[a]);
  return { pct, H, sumW, ranked, lead: ranked[0] };
}

