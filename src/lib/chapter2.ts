// pct1/pct2 — проценты по каждому полюсу за главу 1 и главу 2 (как они были
// зафиксированы в момент прохождения — берём из measurements, а не
// пересчитываем на лету, чтобы правки формул не сдвигали историю).
export function computeResonance(pct1: Record<string, number>, lead1: string, pct2: Record<string, number>) {
  const delta = Math.abs((pct1[lead1] || 0) - (pct2[lead1] || 0));
  const level = delta <= 10 ? "high" : delta <= 19 ? "partial" : "gap";
  return { delta: Math.round(delta), level };
}

