/* ------------------------------------------------------------------ */
/*  Объединённый профиль глагола (глава 3 + повторный сигнал главы 7)   */
/* ------------------------------------------------------------------ */

export function combineVerbProfile(measurements: any[]) {
  const acc = {};
  VERBS.forEach((v) => (acc[v] = { sw: 0, swv: 0 }));
  measurements.forEach((m) => {
    if (m.kind !== "ipsative") return;
    if (!acc[m.pole]) return;
    acc[m.pole].sw += m.weight;
    acc[m.pole].swv += m.weight * m.value;
  });
  const pct = {};
  VERBS.forEach((v) => (pct[v] = acc[v].sw > 0 ? acc[v].swv / acc[v].sw : 0));
  const sumW = VERBS.reduce((s, v) => Math.max(s, acc[v].sw), 0);
  let H = sumW > 0 ? (25 / Math.sqrt(sumW)) * Math.sqrt(6 / 4) : 25;
  H = Math.max(4, Math.min(30, H));
  const ranked = [...VERBS].sort((a, b) => pct[b] - pct[a]);
  return { pct, H, sumW, ranked, lead: ranked[0] };
}

/* ------------------------------------------------------------------ */
/*  Скоринг главы 3                                                    */
/* ------------------------------------------------------------------ */

export function computeResult3(answers: Record<string, unknown>) {
  const raw = {};
  VERBS.forEach((v) => (raw[v] = 0));
  let sumW = 0;

  QUESTIONS3.forEach((q) => {
    if (!IPSATIVE_IDS3.includes(q.id)) return;
    const a = answers[q.id];
    if (a == null) return;
    sumW += q.weight;

    if (q.kind === "single") {
      const opt = q.options.find((o) => o.id === a);
      if (opt) Object.entries(opt.score).forEach(([p, v]) => (raw[p] += v * q.weight));
    }
    if (q.kind === "distribute") {
      q.items.forEach((item) => {
        raw[item.pole] += (a[item.pole] || 0) * q.weight;
      });
    }
  });

  const total = VERBS.reduce((s, p) => s + raw[p], 0) || 1;
  const pct = {};
  VERBS.forEach((p) => (pct[p] = (raw[p] / total) * 100));

  // нормативные: Q10 калибрует Со/Чи в паре, Q11 калибрует Пе
  const norm = {};
  const q10 = answers.c3q10;
  if (q10 != null) {
    norm.SO = ((q10 - 1) / 4) * 100;
    norm.CHI = 100 - norm.SO;
  }
  const q11 = answers.c3q11;
  if (q11 != null) {
    norm.PE = ((q11 - 1) / 4) * 100;
  }

  let H = 25 / Math.sqrt(sumW || 1) * Math.sqrt(6 / 4); // корректировка на 6 полюсов вместо 4
  H = Math.max(4, Math.min(30, H));

  const ranked = [...VERBS].sort((a, b) => pct[b] - pct[a]);
  const lead = ranked[0];
  const second = ranked[1];
  const flat = pct[lead] < 22;

  const q12Opt = QUESTIONS3.find((q) => q.id === "c3q12").options.find(
    (o) => o.id === answers.c3q12
  );
  const q12Pole = q12Opt ? Object.keys(q12Opt.score)[0] : null;

  return { raw, pct, norm, sumW, H, ranked, lead, second, flat, q12Pole };
}

/* ------------------------------------------------------------------ */
/*  Перекрёстная проверка с предметом труда (главы 1–2)                */
/*  Спецификация описывает её явно только для полюса «Люди» —          */
/*  остальные не обобщаем, чтобы не выдумывать за автора.               */
/* ------------------------------------------------------------------ */

export function crossCheck3(materialLead: string, verbLead: string) {
  if (materialLead !== "L") return null;
  if (verbLead === "PE" || verbLead === "UB") return null;
  return { materialLead, verbLead };
}

