const POLE_NAMES3 = { L: "люди", S: "системы", M: "материя", O: "образы" };
const VERB_GERUND = {
  SO: "создавать", CHI: "чинить и улучшать", IS: "исследовать", OR: "организовывать", PE: "объяснять", UB: "убеждать",
};

// формула по умолчанию для остальных 21 сочетания — собирается из уже
// написанных текстов по глаголу + названия поля, без выдумывания нового стиля
export function linkText3(materialPole: string, verbPole: string) {
  const key = `${materialPole}-${verbPole}`;
  if (LINKS3_AUTHORED[key]) return LINKS3_AUTHORED[key];
  const v = TEXTS3[verbPole];
  return {
    title: `Ты — тот, кто ${VERB_GERUND[verbPole]} в поле «${POLE_NAMES3[materialPole]}»`,
    body: `Твой материал — ${POLE_NAMES3[materialPole]}. Твоё действие — ${VERB_GERUND[verbPole]}. ${v.body}`,
    focus: v.where,
  };
}

