export function computeResult6(answers: Record<string, unknown>, verbLead: string, verbFlat: boolean) {
  const sum = {};
  const w = {};
  SUBSCALES.forEach((s) => { sum[s] = 0; w[s] = 0; });

  QUESTIONS6.forEach((q) => {
    const a = answers[q.id];
    if (a == null) return;

    if (q.kind === "scale6") {
      const s100 = ((a - 1) / 4) * 100;
      sum[q.sub] += s100 * q.weight;
      w[q.sub] += q.weight;
    }
  });

  // c6a8 — дихотомия приоритизации: усиливает одну субшкалу, смягчает другую
  const a8 = answers.c6a8;
  if (a8) {
    const q8 = QUESTIONS6.find((q) => q.id === "c6a8");
    if (a8 === "a") {
      // выбрал непредсказуемый доход → публичность отталкивает сильнее
      sum.public += 100 * q8.weight;
      w.public += q8.weight;
      sum.risk += 20 * q8.weight;
      w.risk += q8.weight;
    } else {
      sum.risk += 100 * q8.weight;
      w.risk += q8.weight;
      sum.public += 20 * q8.weight;
      w.public += q8.weight;
    }
  }

  const score = {};
  const H = {};
  SUBSCALES.forEach((s) => {
    score[s] = w[s] > 0 ? sum[s] / w[s] : 0;
    H[s] = w[s] > 0 ? Math.max(4, Math.min(30, 25 / Math.sqrt(w[s]))) : 30;
  });

  // финальный список исключений: 3-5 субшкал ≥60 по убыванию;
  // если таких меньше трёх — берём три верхних с пометкой «мягкое»
  const ranked = [...SUBSCALES].sort((a, b) => score[b] - score[a]);
  const strong = ranked.filter((s) => score[s] >= 60);
  const soft = strong.length < 3;
  const exclusions = (soft ? ranked.slice(0, 3) : strong.slice(0, 5));

  /* --- флаг противоречия --------------------------------------- */
  const cq = contradictionQuestion(verbLead, verbFlat);
  const ca = answers[CONTRADICTION_ID];
  let contradiction = null;
  if (ca != null) {
    const s100 = ((ca - 1) / 4) * 100;
    const rule = cq._bank.contradictionWhen;
    const isHigh = s100 >= 60;
    const isLow = s100 < 35;
    if (rule === "high" && isHigh) contradiction = { sub: cq._bank.sub, verbLead };
    else if (rule === "low" && isLow) contradiction = { sub: cq._bank.sub, verbLead };
  }

  return { score, H, ranked, exclusions, soft, contradiction };
}

export function isComplete6(q, a) {
  return a != null;
}

