export function contradictionQuestion(verbLead: string, verbFlat: boolean) {
  const bank = verbFlat || !verbLead ? CONTRA_BANK.SO : (CONTRA_BANK[verbLead] || CONTRA_BANK.SO);
  return {
    id: CONTRADICTION_ID,
    kind: "scale6",
    sub: bank.sub,
    weight: 0, // не идёт в баллы — только во флаг
    tag: "последний — сверим с тем, что мы уже о тебе знаем",
    text: bank.text,
    _bank: bank,
  };
}

